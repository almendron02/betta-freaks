type CatalogFilters = { sex?: ProductSex | "all"; type?: ProductType | "all" };

export const getCatalogProducts = ({ sex = "all", type = "all" }: CatalogFilters = {}) =>
  sampleProducts.filter((product) => product.status === "active" && (sex === "all" || product.sex === sex) && (type === "all" || product.type === type));

export const getProductBySlug = (slug: string) => sampleProducts.find((product) => product.slug === slug && product.status === "active");
